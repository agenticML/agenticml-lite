"""SQL variations kept outside repositories."""
import hashlib
import json
import re

_IDENT = re.compile(r'^[a-z_][a-z0-9_]*$')


class SqliteDialect:
    name = 'sqlite'

    def placeholders(self, sql):
        return sql

    def migration(self, sql):
        for token, value in {"id": "INTEGER PRIMARY KEY", "blob": "BLOB", "real": "REAL"}.items():
            sql = sql.replace("{{" + token + "}}", value)
        return sql

    def lock_row(self, tx, table, where_sql, params=()):
        # BEGIN IMMEDIATE already holds the database write lock.
        pass

    def advisory_lock(self, tx, name):
        pass

    def enable_workspace_rls(self, tx, table):
        """No-op on SQLite. Postgres enables FORCE RLS for ``table``.

        REQUIRED for any later migration that adds a workspace-scoped table.
        0006 covers tables that exist at 19.2; it will not run again for
        tables added afterwards.
        """
        pass

    def upsert(self, table, columns, conflict, updates):
        names = ', '.join(columns)
        values = ', '.join('?' for _ in columns)
        action = ('DO UPDATE SET ' + ', '.join(f'{c}=excluded.{c}' for c in updates)
                  if updates else 'DO NOTHING')
        return (f'INSERT INTO {table} ({names}) VALUES ({values}) '
                f'ON CONFLICT ({", ".join(conflict)}) {action}')


class PostgresDialect(SqliteDialect):
    name = 'postgres'

    def placeholders(self, sql):
        return sql.replace('%', '%%').replace('?', '%s')

    def migration(self, sql):
        for token, value in {
            'id': 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',
            'blob': 'BYTEA', 'real': 'DOUBLE PRECISION',
        }.items():
            sql = sql.replace('{{' + token + '}}', value)
        return sql

    @staticmethod
    def _scope(tx):
        connection = tx.connection
        scope = getattr(connection, '_agenticml_lock_scope', None)
        if scope is None:
            row = tx.fetchone('SELECT current_database(), current_schema()')
            scope = (row[0], row[1])
            connection._agenticml_lock_scope = scope
        return scope

    @staticmethod
    def _lock(tx, name):
        kind, _, rest = name.partition(':')
        salted = kind + ':' + str(PostgresDialect._scope(tx)) + ':' + rest
        key = int.from_bytes(hashlib.sha256(salted.encode()).digest()[:8],
                             byteorder='big', signed=True)
        tx.execute('SELECT pg_advisory_xact_lock(?)', (key,))

    def lock_row(self, tx, table, where_sql, params=()):
        self._lock(tx, 'row:' + table + ':' + json.dumps(params))

    def advisory_lock(self, tx, name):
        self._lock(tx, 'name:' + name)

    def enable_workspace_rls(self, tx, table):
        """ENABLE/FORCE RLS and (re)create ``<table>_workspace``.

        REQUIRED for any later migration that adds a workspace-scoped table.
        0006 covers tables that exist at 19.2; it will not run again for
        tables added afterwards.
        """
        if _IDENT.fullmatch(table) is None:
            raise RuntimeError(f'refusing to enable RLS on {table!r}')
        tx.execute(f'ALTER TABLE {table} ENABLE ROW LEVEL SECURITY')
        tx.execute(f'ALTER TABLE {table} FORCE ROW LEVEL SECURITY')
        tx.execute(f'DROP POLICY IF EXISTS {table}_workspace ON {table}')
        tx.execute(
            f'CREATE POLICY {table}_workspace ON {table} '
            "USING (workspace_id = current_setting('app.workspace_id', true) "
            "OR current_setting('app.workspace_id', true) = '*') "
            "WITH CHECK (workspace_id = current_setting('app.workspace_id', true) "
            "OR current_setting('app.workspace_id', true) = '*')")
